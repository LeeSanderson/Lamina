using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Lamina.XunitV3.Generators;

/// <summary>
/// Expands an abstract spec class marked <c>[Channels(...)]</c> into one sealed <c>&lt;Class&gt;_&lt;Channel&gt;</c> subclass per channel,
/// each carrying <c>[Trait("Channel", "&lt;channel&gt;")]</c>. The spec base reads the channel from that trait.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ChannelGenerator : IIncrementalGenerator
{
    private const string ChannelsAttribute = "Lamina.XunitV3.ChannelsAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var channelClasses = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                ChannelsAttribute,
                static (node, _) => node is ClassDeclarationSyntax,
                static (attributed, _) => ChannelClassesFor(attributed))
            .SelectMany(static (classes, _) => classes);

        context.RegisterSourceOutput(channelClasses, static (output, channelClass) => output.AddSource(channelClass.HintName, channelClass.Source));
    }

    private static ImmutableArray<ChannelClass> ChannelClassesFor(GeneratorAttributeSyntaxContext attributed)
    {
        if (attributed.TargetSymbol is not INamedTypeSymbol { IsAbstract: true, IsGenericType: false, ContainingType: null } spec)
        {
            return ImmutableArray<ChannelClass>.Empty;
        }

        return attributed.Attributes
            .SelectMany(attribute => attribute.ConstructorArguments)
            .SelectMany(argument => argument.Kind == TypedConstantKind.Array ? argument.Values : ImmutableArray.Create(argument))
            .Select(channel => channel.Value)
            .OfType<string>()
            .Distinct(System.StringComparer.Ordinal)
            .Select(channel => ChannelClass.For(spec, channel))
            .ToImmutableArray();
    }

    private sealed record ChannelClass(string HintName, string Source)
    {
        internal static ChannelClass For(INamedTypeSymbol spec, string channel)
        {
            var className = $"{spec.Name}_{Identifier(channel)}";
            var specNamespace = spec.ContainingNamespace.IsGlobalNamespace ? null : spec.ContainingNamespace.ToDisplayString();
            var accessibility = spec.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";
            var baseClass = spec.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var trait = SymbolDisplay.FormatLiteral(channel, quote: true);

            var source = new StringBuilder()
                .AppendLine("// <auto-generated/>")
                .AppendLine("#nullable enable")
                .AppendLine();
            var indent = string.Empty;
            if (specNamespace is not null)
            {
                source.AppendLine($"namespace {specNamespace}").AppendLine("{");
                indent = "    ";
            }

            source
                .AppendLine($"{indent}[global::Xunit.Trait(\"Channel\", {trait})]")
                .AppendLine($"{indent}{accessibility} sealed class {className} : {baseClass}")
                .AppendLine($"{indent}{{")
                .AppendLine($"{indent}}}");
            if (specNamespace is not null)
            {
                source.AppendLine("}");
            }

            var hintName = specNamespace is null ? $"{className}.g.cs" : $"{specNamespace}.{className}.g.cs";
            return new ChannelClass(hintName, source.ToString());
        }

        private static string Identifier(string channel)
        {
            var identifier = new StringBuilder();
            var startOfWord = true;
            foreach (var character in channel)
            {
                if (!char.IsLetterOrDigit(character))
                {
                    startOfWord = true;
                    continue;
                }

                identifier.Append(startOfWord ? char.ToUpperInvariant(character) : character);
                startOfWord = false;
            }

            return identifier.ToString();
        }
    }
}
