using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Spike.Channels.Generator;

[Generator(LanguageNames.CSharp)]
public sealed class ChannelGenerator : IIncrementalGenerator
{
    private const string ChannelsAttributeName = "Spike.Channels.ChannelsAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var specs = context.SyntaxProvider.ForAttributeWithMetadataName(
            ChannelsAttributeName,
            static (node, _) => node is Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax,
            static (ctx, _) => ToSpec(ctx));

        var framework = context.CompilationProvider.Select(static (compilation, _) => DetectFramework(compilation));
        var omitInheritsTests = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.SpikeOmitInheritsTests", out var value)
            && string.Equals(value, "true", System.StringComparison.OrdinalIgnoreCase));

        var inputs = specs.Combine(framework).Combine(omitInheritsTests);
        context.RegisterSourceOutput(inputs, static (output, input) =>
        {
            var ((spec, testFramework), omit) = input;
            foreach (var channel in spec.Channels)
            {
                var className = spec.ClassName + "_" + ToPascal(channel);
                output.AddSource(
                    spec.Namespace + "." + className + ".g.cs",
                    SourceText.From(Emit(spec, className, channel, testFramework, omit), Encoding.UTF8));
            }
        });
    }

    private static SpecModel ToSpec(GeneratorAttributeSyntaxContext ctx)
    {
        var symbol = ctx.TargetSymbol;
        var channels = ctx.Attributes[0].ConstructorArguments
            .SelectMany(static arg => arg.Kind == TypedConstantKind.Array ? arg.Values : ImmutableArray.Create(arg))
            .Select(static value => value.Value as string)
            .Where(static value => !string.IsNullOrEmpty(value))
            .Select(static value => value!)
            .ToImmutableArray();
        return new SpecModel(symbol.ContainingNamespace.ToDisplayString(), symbol.Name, new EquatableArray(channels));
    }

    private static TestFramework DetectFramework(Compilation compilation)
    {
        if (compilation.GetTypeByMetadataName("TUnit.Core.InheritsTestsAttribute") is not null)
        {
            return TestFramework.TUnit;
        }

        if (compilation.GetTypeByMetadataName("NUnit.Framework.TestAttribute") is not null)
        {
            return TestFramework.NUnit;
        }

        return compilation.GetTypeByMetadataName("Xunit.TraitAttribute") is not null ? TestFramework.XunitV3 : TestFramework.None;
    }

    private static string Emit(SpecModel spec, string className, string channel, TestFramework framework, bool omitInheritsTests)
    {
        var attributes = framework switch
        {
            TestFramework.XunitV3 => $"[global::Xunit.Trait(\"Channel\", \"{channel}\")]",
            TestFramework.NUnit => $"[global::NUnit.Framework.Property(\"Channel\", \"{channel}\")]",
            TestFramework.TUnit => (omitInheritsTests ? string.Empty : "[global::TUnit.Core.InheritsTests]\n")
                + $"[global::TUnit.Core.Property(\"Channel\", \"{channel}\")]",
            _ => string.Empty,
        };

        return $$"""
            // <auto-generated/>
            #nullable enable
            namespace {{spec.Namespace}}
            {
            {{attributes}}
            public sealed class {{className}} : {{spec.ClassName}}
            {
                protected override string Channel => "{{channel}}";
            }
            }

            """;
    }

    private static string ToPascal(string channel) =>
        channel.Length == 0 ? channel : char.ToUpperInvariant(channel[0]) + channel.Substring(1);

    private enum TestFramework
    {
        None,
        XunitV3,
        TUnit,
        NUnit,
    }

    private sealed class SpecModel(string @namespace, string className, EquatableArray channels) : System.IEquatable<SpecModel>
    {
        public string Namespace { get; } = @namespace;

        public string ClassName { get; } = className;

        public EquatableArray Channels { get; } = channels;

        public bool Equals(SpecModel? other) =>
            other is not null
            && string.Equals(Namespace, other.Namespace, System.StringComparison.Ordinal)
            && string.Equals(ClassName, other.ClassName, System.StringComparison.Ordinal)
            && Channels.Equals(other.Channels);

        public override bool Equals(object? obj) => Equals(obj as SpecModel);

        public override int GetHashCode() => System.StringComparer.Ordinal.GetHashCode(ClassName);
    }

    private sealed class EquatableArray(ImmutableArray<string> items) : System.IEquatable<EquatableArray>, IEnumerable<string>
    {
        public bool Equals(EquatableArray? other) => other is not null && items.SequenceEqual(other.ToImmutableArray());

        public override bool Equals(object? obj) => Equals(obj as EquatableArray);

        public override int GetHashCode() => items.Length;

        public IEnumerator<string> GetEnumerator() => items.AsEnumerable().GetEnumerator();

        System.Collections.IEnumerator System.Collections.IEnumerable.GetEnumerator() => GetEnumerator();

        private ImmutableArray<string> ToImmutableArray() => items;
    }
}
